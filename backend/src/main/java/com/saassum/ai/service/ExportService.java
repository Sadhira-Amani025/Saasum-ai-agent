    public byte[] generateExportZip(String websiteConfigJson) throws Exception {
        JsonNode root = objectMapper.readTree(websiteConfigJson);

        String brandName = root.path("meta").path("brandName").asText("SaaSsum Website");
        String title = root.path("meta").path("title").asText(brandName);
        String tagline = root.path("meta").path("tagline").asText("");

        JsonNode theme = root.path("theme");
        String primaryColor = theme.path("primaryColor").asText("#6366f1");
        String secondaryColor = theme.path("secondaryColor").asText("#a855f7");
        String bgColor = theme.path("backgroundColor").asText("#0b0f19");
        String textColor = theme.path("textColor").asText("#f9fafb");
        String cardBg = theme.path("cardBackground").asText("#111827");
        String radius = theme.path("borderRadius").asText("12px");
        String fontFamily = theme.path("fontFamily").asText("Inter, sans-serif");
        boolean isDark = theme.path("isDark").asBoolean(true);

        // Generate HTML
        StringBuilder html = new StringBuilder();
        html.append("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n");
        html.append("  <meta charset=\"UTF-8\">\n");
        html.append("  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n");
        html.append("  <title>").append(escapeHtml(title)).append("</title>\n");
        html.append("  <meta name=\"description\" content=\"").append(escapeHtml(tagline)).append("\">\n");
        html.append("  <link rel=\"stylesheet\" href=\"style.css\">\n");
        html.append("  <link href=\"https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&family=Playfair+Display:ital,wght@0,600;1,400&display=swap\" rel=\"stylesheet\">\n");
        html.append("</head>\n<body>\n");

        JsonNode sections = root.path("sections");
        if (sections.isArray()) {
            for (JsonNode sec : sections) {
                renderSectionHtml(sec, html);
            }
        }

        html.append("  <script src=\"script.js\"></script>\n");
        html.append("</body>\n</html>\n");

        // Generate CSS
        String css = generateCss(primaryColor, secondaryColor, bgColor, textColor, cardBg, radius, fontFamily, isDark);

        // Generate JS
        String js = generateJs();

        // Generate README
        String readme = "# " + brandName + " - Official Website Package\n\n" +
                "Generated by **SaaSsum AI Commerce** (From Business Idea to Digital Business in Minutes).\n\n" +
                "## 📁 Package Contents\n" +
                "- `index.html` - Semantic, responsive website layout\n" +
                "- `style.css` - Custom styling & responsive breakpoints\n" +
                "- `script.js` - Interactive accordions, smooth scrolling, and navigation\n\n" +
                "## 🚀 Quick Run Locally\n" +
                "Double click `index.html` in your browser, or run:\n" +
                "```bash\npython -m http.server 8080\n```\n\n" +
                "## 🌐 1-Click Free Hosting\n" +
                "- **Netlify Drop**: Drag and drop this folder at [app.netlify.com/drop](https://app.netlify.com/drop)\n" +
                "- **GitHub Pages**: Push this directory to GitHub and turn on Pages in Repository Settings.\n";

        // Package into ZIP
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        try (ZipOutputStream zos = new ZipOutputStream(baos)) {
            addZipEntry(zos, "index.html", html.toString());
            addZipEntry(zos, "style.css", css);
            addZipEntry(zos, "script.js", js);
            addZipEntry(zos, "README.md", readme);
        }

        return baos.toByteArray();
    }

